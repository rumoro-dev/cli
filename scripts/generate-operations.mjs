// Writes src/generated/operations.ts from the SDK's OpenAPI document (packages/sdk/openapi.json): one entry per
// operation with its parameters and body fields, which the CLI turns into one noun:verb command each.
import { readFileSync, writeFileSync } from "node:fs";

const document = JSON.parse(readFileSync(new URL("../../sdk/openapi.json", import.meta.url), "utf8"));
const resolve = (schema) => (schema?.$ref ? resolve(document.components.schemas[schema.$ref.split("/").pop()]) : schema ?? {});
const typeOf = (schema) => {
  const resolved = resolve(schema);
  if (resolved.type) return resolved.type;
  if (resolved.properties || resolved.oneOf || resolved.anyOf || resolved.allOf) return "object";
  return "string";
};

function field(name, schema, { required, description, location }) {
  const resolved = resolve(schema), type = typeOf(schema);
  const values = type === "array" ? resolve(resolved.items).enum : resolved.enum;
  const text = description ?? resolved.description;
  return {
    name,
    ...(location ? { in: location } : {}),
    type,
    ...(text ? { description: text } : {}),
    ...(values ? { enum: values } : {}),
    required: Boolean(required),
    // A parameter is never null on the command line: "null" clears body fields only.
    nullable: !location && Boolean(resolved.nullable),
    ...(type === "array" && !location ? { items: typeOf(resolved.items) } : {}),
  };
}

function bodyFields(schema) {
  const resolved = resolve(schema);
  // A union (createChannel): every variant's fields, none required, enums merged.
  if (resolved.oneOf || resolved.anyOf) {
    const merged = new Map();
    for (const variant of resolved.oneOf ?? resolved.anyOf) for (const item of bodyFields(variant)) {
      const known = merged.get(item.name);
      if (!known) merged.set(item.name, { ...item, required: false });
      else if (known.enum && item.enum) known.enum = [...new Set([...known.enum, ...item.enum])];
    }
    return [...merged.values()];
  }
  const required = new Set(resolved.required ?? []);
  return Object.entries(resolved.properties ?? {}).map(([name, property]) => field(name, property, { required: required.has(name) }));
}

const operations = [];
for (const [path, methods] of Object.entries(document.paths)) for (const [method, operation] of Object.entries(methods)) {
  const success = Object.entries(operation.responses).find(([status]) => status.startsWith("2"))?.[1];
  const content = Object.keys(success?.content ?? {});
  const json = operation.requestBody?.content?.["application/json"]?.schema;
  operations.push({
    operationId: operation.operationId,
    method: method.toUpperCase(),
    path,
    summary: operation.summary ?? operation.operationId,
    ...(operation.description ? { description: operation.description } : {}),
    tag: operation.tags?.[0] ?? "Other",
    params: (operation.parameters ?? []).map((parameter) => field(parameter.name, parameter.schema,
      { required: parameter.required, description: parameter.description, location: parameter.in })),
    body: json ? { fields: bodyFields(json) } : null,
    response: content.length === 0 ? "none" : content.includes("text/csv") ? "csv" : "json",
  });
}

const target = new URL("../src/generated/operations.ts", import.meta.url);
writeFileSync(target, `// Generated by scripts/generate-operations.mjs from the API's OpenAPI document. Do not edit.
import type { Operation } from "../types";

export const OPERATIONS: Operation[] = ${JSON.stringify(operations, null, 2)};
`);
console.log(`${operations.length} operations`);
